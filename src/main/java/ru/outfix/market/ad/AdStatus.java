package ru.outfix.market.ad;

public enum AdStatus {
    /** Ждёт решения модератора. */
    PENDING,
    /** Опубликовано в канале объявлений. */
    PUBLISHED,
    /** Отклонено модератором (может быть одобрено позже). */
    REJECTED,
    /** Снято с публикации: продано. */
    SOLD,
    /** Снято с публикации: не продано. */
    REMOVED
}
